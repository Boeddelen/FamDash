const dicts: Record<Locale, Dict> = { nb, en };

export type Translator = (key: string, params?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translator {
	const dict = dicts[locale] ?? nb;
	return (key, params) => {
		let s = dict[key] ?? en[key] ?? key;
		if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
		return s;
	};
}

const KEY = Symbol('i18n');

export function provideI18n(locale: Locale) {
	const t = createTranslator(locale);
	setContext(KEY, { t, locale });
	return t;
}

export function getI18n(): { t: Translator; locale: Locale } {
	return getContext(KEY) ?? { t: createTranslator('nb'), locale: 'nb' as Locale };
}

/** Locale-aware date helpers for the browser. */
export function localeTag(locale: Locale): string {
	return locale === 'nb' ? 'nb-NO' : 'en-GB';
}
